let lines = [],
  num = 0;
function circuit(n) {
  if (n.value !== undefined) return String(n.value);
  const i = num++;
  const left = circuit(n.left),
    right = circuit(n.right);
  lines.push(
    `component node${i} = LessThan(8); node${i}.in[0] <== features[${n.feature}]; node${i}.in[1] <== ${n.threshold}; signal result${i}; result${i} <== (${left}-${right}) * node${i}.out + ${right};`,
  );
  return `result${i}`;
}
